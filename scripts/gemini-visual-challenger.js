#!/usr/bin/env node
/**
 * gemini-visual-challenger.js — Gemini as semantic reviewer/judge.
 *
 * Receives OpenCode's visual intent document and reviews it:
 * - MATCH: intent is sound, proceed to rendering
 * - NEEDS_CHANGE: intent has issues, provide specific deltas
 *
 * This is the ONLY Gemini call in the normal video flow.
 * Gemini does NOT generate the plan — it challenges OpenCode's plan.
 *
 * Usage:
 *   node scripts/gemini-visual-challenger.js --intent <path> --script <path> --channel <id> --out <review.json>
 */
import "dotenv/config";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { callGemini } from "../src/lib/gemini-client.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

function arg(name, fallback = null) {
  const i = process.argv.indexOf("--" + name);
  if (i > -1 && process.argv[i + 1]) return process.argv[i + 1];
  return fallback;
}

function buildChallengerPrompt(intent, scriptText, channelConfig) {
  const beatSummaries = intent.beats.map(b =>
    `[${b.index}] purpose: "${b.narrative_purpose}" | event: "${b.visual_event}" | object: "${b.key_object}" | transformation: "${b.transformation}" | headline: "${b.visual_headline || "none"}" | confidence: ${b.confidence}`
  ).join("\n");

  const niche = channelConfig?.niche || "general";

  return `You are the VISUAL REVIEWER for a YouTube Shorts video.
Channel niche: ${niche}

You receive a VISUAL INTENT DOCUMENT generated by another system.
Your job is to CHALLENGE it — find weak visual decisions, missed opportunities,
and errors. You are a JUDGE, not a generator.

For each beat, evaluate:
1. Does the visual_event actually serve the narrative_purpose?
2. Is the key_object specific enough to visualize (not abstract)?
3. Does the transformation show CHANGE (not just a static scene)?
4. Would a viewer with NO audio understand the muted_read?
5. Is the consequence achievable through visual means alone?
6. Are consecutive beats visually diverse (not the same event repeated)?

VERDICT:
- "MATCH": All beats are sound. No changes needed. Proceed to rendering.
- "NEEDS_CHANGE": One or more beats have issues. Provide specific deltas.

Deltas format:
{
  "beat_index": <number>,
  "field": "<which field needs change>",
  "current": "<current value>",
  "suggested": "<better value>",
  "reason": "<why this change improves the beat>"
}

SCRIPT:
${scriptText}

VISUAL INTENT DOCUMENT:
Visual argument: ${intent.visual_argument}
${beatSummaries}

Respond ONLY with JSON (no markdown fences):
{
  "verdict": "MATCH" | "NEEDS_CHANGE",
  "overall_score": <1-10>,
  "strengths": ["<what works well>"],
  "weaknesses": ["<what needs improvement>"],
  "deltas": [
    {
      "beat_index": <number>,
      "field": "<field name>",
      "current": "<current value>",
      "suggested": "<better value>",
      "reason": "<why>"
    }
  ],
  "summary": "<one sentence overall assessment>"
}`;
}

async function main() {
  const intentPath = arg("intent");
  const scriptPath = arg("script");
  const channelId = arg("channel");
  const outPath = arg("out");

  if (!intentPath || !outPath) {
    console.error("Usage: gemini-visual-challenger.js --intent <path> --script <path> --channel <id> --out <review.json>");
    process.exit(2);
  }

  const intent = JSON.parse(readFileSync(intentPath, "utf-8"));

  // Load script text
  let scriptText = "";
  if (scriptPath && existsSync(scriptPath)) {
    const scriptData = JSON.parse(readFileSync(scriptPath, "utf-8"));
    scriptText = scriptData.voiceover_text || scriptData.script || JSON.stringify(scriptData).slice(0, 2000);
  }

  // Load channel config
  let channelConfig = null;
  if (channelId) {
    try {
      const config = JSON.parse(readFileSync(join(ROOT, "config", "channels.json"), "utf-8"));
      channelConfig = config.channels.find(c => String(c.id) === String(channelId));
    } catch {}
  }

  console.log(`Challenging visual intent (${intent.beats.length} beats)...`);
  const prompt = buildChallengerPrompt(intent, scriptText, channelConfig);
  const result = await callGemini([{ role: "user", content: prompt }], { maxTokens: 4096, temperature: 0.3 });

  let review;
  if (result?.content && typeof result.content === "string") {
    try {
      review = JSON.parse(result.content);
    } catch {
      console.error("Failed to parse Gemini response as JSON");
      review = { verdict: "MATCH", overall_score: 7, strengths: [], weaknesses: ["parse error"], deltas: [], summary: "Could not parse review" };
    }
  } else if (result?.beats) {
    // Already parsed
    review = result;
  } else {
    console.error("Gemini returned no content");
    review = { verdict: "MATCH", overall_score: 7, strengths: [], weaknesses: ["no response"], deltas: [], summary: "No response from reviewer" };
  }

  const output = {
    reviewedAt: new Date().toISOString(),
    source: "gemini-challenger",
    verdict: review.verdict || "MATCH",
    overall_score: review.overall_score || 7,
    strengths: review.strengths || [],
    weaknesses: review.weaknesses || [],
    deltas: review.deltas || [],
    summary: review.summary || "",
    intent_file: intentPath,
  };

  writeFileSync(outPath, JSON.stringify(output, null, 2) + "\n");
  console.log(`Review written: ${outPath}`);
  console.log(`  Verdict: ${output.verdict}`);
  console.log(`  Score: ${output.overall_score}/10`);
  console.log(`  Deltas: ${output.deltas.length}`);
  if (output.deltas.length) {
    for (const d of output.deltas) {
      console.log(`    [${d.beat_index}] ${d.field}: "${d.current}" → "${d.suggested}" (${d.reason})`);
    }
  }
}

main().catch(e => {
  console.error(`Fatal error: ${e.message}`);
  process.exit(1);
});