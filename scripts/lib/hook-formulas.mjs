/**
 * The hook formulas the writer prompt offers (prompts/hooks/hooks.json, from github.com/Jakeschincariol/youtube-agent-skill, MIT;
 * see prompts/hooks/README.md). Only the formulas that fit a faceless channel whose every figure comes from the research are used:
 * the creator-centric ones (i-tried-it, the-origin, the-receipt, the-insider, the-stack, the-direct-address, the-mistake, the-reveal,
 * the-clock, the-teardown, someone-elses-result) need the narrator's own experience, a screenshot of their own work, or an invented
 * result, none of which this pipeline may state.
 */
import { readFileSync } from "node:fs";

export const FACELESS_FORMULAS = [
  "the-statistic", "the-superlative", "contrarian-flip", "the-question", "the-before-after",
  "the-warning", "the-list", "the-impossible", "the-comparison", "the-deadline",
];

export const BEGIN = "<!-- HOOK-FORMULAS:BEGIN (generated by scripts/lib/hook-formulas.mjs; do not edit by hand) -->";
export const END = "<!-- HOOK-FORMULAS:END -->";

export function loadFormulas(path = new URL("../../prompts/hooks/hooks.json", import.meta.url)) {
  const all = JSON.parse(readFileSync(path, "utf8")).hooks;
  return FACELESS_FORMULAS.map((id) => {
    const f = all.find((h) => h.id === id);
    if (!f) throw new Error(`hook formula ${id} is missing from prompts/hooks/hooks.json`);
    return f;
  });
}

export function renderHookSection(formulas = loadFormulas()) {
  const lines = formulas.map((f) => `- **${f.name}**: ${f.shape} Fails when: ${f.fails_when}`);
  return `${BEGIN}
**Hook formulas (proven shapes; pick the ONE the research supports best).** Every figure, name, date and comparison in the hook
still comes from the research: a formula that needs a number is used only when the research states that number, and never with a
rounded-up or invented one. Do not pick the same formula as the title's obvious pattern every time: vary it across videos.
${lines.join("\n")}
Never use a formula that needs the narrator's own experience, a screenshot of their own work or inside access: this channel has none.
${END}`;
}

/** Replace the generated block of a prompt (or insert it after `anchor`). Returns the new text. */
export function withHookSection(prompt, anchor = "   a person's name first, \"According to\", \"The report\".") {
  const block = renderHookSection();
  const b = prompt.indexOf(BEGIN);
  const e = prompt.indexOf(END);
  if (b >= 0 && e > b) return prompt.slice(0, b) + block + prompt.slice(e + END.length);
  const i = prompt.indexOf(anchor);
  if (i < 0) throw new Error("hook-formulas: anchor line not found in the writer prompt");
  const at = i + anchor.length;
  return `${prompt.slice(0, at)}\n${block}${prompt.slice(at)}`;
}

if (process.argv[1] && /hook-formulas\.mjs$/.test(process.argv[1].split("\\").join("/"))) {
  const { readFileSync: rd, writeFileSync: wr } = await import("node:fs");
  const p = new URL("../../prompts/write-script.md", import.meta.url);
  wr(p, withHookSection(rd(p, "utf8").split("\r").join("")));
  console.log("prompts/write-script.md: hook formula block written");
}
