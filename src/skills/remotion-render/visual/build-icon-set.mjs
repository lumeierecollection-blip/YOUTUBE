#!/usr/bin/env node
/**
 * Generate visual/icon-set.js from the vendored Lucide SVGs in public/icons/.
 *
 *   node src/skills/remotion-render/visual/build-icon-set.mjs          # write
 *   node src/skills/remotion-render/visual/build-icon-set.mjs --check  # exit 1 if stale
 *
 * The renderer needs the icon GEOMETRY, not an <img>: MOTION-GRAPHICS-MANUAL
 * §A4.3 requires the stroke width to be recomputed at video scale, and §A4.5
 * requires the colour to come from the palette. Neither is possible through
 * an <img> of a currentColor SVG. So each icon is parsed once into a list of
 * [tag, attrs] elements and emitted as a plain .js module that the Remotion
 * bundle, the planner (node) and the validator all import — the same
 * single-source rule as scene-primitives.js.
 *
 * Lucide icons use only path/line/polyline/polygon/circle/ellipse/rect with
 * no transforms (§A4.2), which is all this parser handles. Anything else
 * fails the build rather than being dropped.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ICON_DIR = join(HERE, "..", "public", "icons");
const OUT = join(HERE, "icon-set.js");
const ALLOWED = new Set(["path", "line", "polyline", "polygon", "circle", "ellipse", "rect"]);

function parseIcon(name, svg) {
  const body = svg.replace(/<svg[^>]*>/, "").replace(/<\/svg>/, "");
  const els = [];
  const re = /<([a-z]+)\b([^>]*?)\/?>/g;
  let m;
  while ((m = re.exec(body))) {
    const tag = m[1];
    if (!ALLOWED.has(tag)) throw new Error(`${name}.svg: unsupported element <${tag}>`);
    const attrs = {};
    const ar = /([a-zA-Z-]+)="([^"]*)"/g;
    let a;
    while ((a = ar.exec(m[2]))) attrs[a[1]] = a[2];
    els.push([tag, attrs]);
  }
  if (!els.length) throw new Error(`${name}.svg: no drawable elements`);
  return els;
}

const names = readdirSync(ICON_DIR).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)).sort();
const set = {};
for (const n of names) set[n] = parseIcon(n, readFileSync(join(ICON_DIR, `${n}.svg`), "utf-8"));

const src = `/**
 * GENERATED by build-icon-set.mjs from public/icons/*.svg — do not edit.
 * Lucide icons, ISC licence (see MOTION-GRAPHICS-MANUAL.md §A4.1).
 * Each icon is a list of [tag, attrs] on Lucide's 24x24 canvas.
 */
export const ICON_SET = ${JSON.stringify(set)};

export const ICON_NAMES = Object.keys(ICON_SET);

export function isIcon(name) {
  return Object.prototype.hasOwnProperty.call(ICON_SET, name);
}
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (cur !== src) {
    console.error("icon-set.js is stale — run build-icon-set.mjs");
    process.exit(1);
  }
  console.log(`icon-set.js up to date (${names.length} icons)`);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT} (${names.length} icons)`);
}
