#!/usr/bin/env node
/**
 * Generate visual/library-names.js — the names the object library registers.
 *
 *   node src/skills/remotion-render/visual/build-library-names.mjs          # write
 *   node src/skills/remotion-render/visual/build-library-names.mjs --check  # exit 1 if stale
 *
 * The drawings live in compositions/objects/{index,library,nature}.jsx and
 * register themselves with registerObject("<name>", fn). The planner and
 * validateScene() run in plain node and cannot import JSX, so the names are
 * read out of those files here and emitted as a plain .js list. The renderer
 * (composed-scene.jsx) compares this list with the live registry when it
 * loads and throws on any difference, so a stale list cannot pass silently.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OBJ_DIR = join(HERE, "..", "compositions", "objects");
const FILES = ["index.jsx", "library.jsx", "nature.jsx"];
const OUT = join(HERE, "library-names.js");

const names = new Set();
for (const f of FILES) {
  const src = readFileSync(join(OBJ_DIR, f), "utf-8");
  for (const m of src.matchAll(/registerObject\(\s*"([^"]+)"/g)) names.add(m[1]);
}
const list = [...names].sort();

const src = `/**
 * GENERATED by build-library-names.mjs from compositions/objects/*.jsx — do not edit.
 * Every name registerObject() registers; the drawings behind the
 * \`library_shape\` primitive (scene-primitives.js).
 */
export const LIBRARY_NAMES = ${JSON.stringify(list, null, 2)};

export function isLibraryName(name) {
  return LIBRARY_NAMES.includes(name);
}
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (cur !== src) {
    console.error("library-names.js is stale — run build-library-names.mjs");
    process.exit(1);
  }
  console.log(`library-names.js up to date (${list.length} drawings)`);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT} (${list.length} drawings)`);
}
