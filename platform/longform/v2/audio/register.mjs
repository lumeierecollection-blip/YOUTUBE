#!/usr/bin/env node
/** Writes docs/longform/SOUND-LIBRARY-REGISTER.md from config/longform-audio-library.json (never hand-typed, so table and measurements cannot drift). */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../../../preview/lib.mjs";

const lib = JSON.parse(readFileSync(join(ROOT, "config/longform-audio-library.json"), "utf8"));
const qa = JSON.parse(readFileSync(join(ROOT, "config/longform-audio-qa.json"), "utf8")).assets;
const reel = Object.fromEntries(JSON.parse(readFileSync(join(ROOT, "output/longform-audio-demo/audition-index.json"), "utf8")).items.map((i) => [i.slot, i.start_s]));
const f = (v, d = 1) => (v === null || v === undefined ? "n/a" : Number(v).toFixed(d));
const rows = lib.assets.map((a) => {
  const m = a.measured || {}, clip = m.true_peak_dbtp > -0.1 ? " **CLIPS**" : "";
  return `| ${a.slot} | ${a.kind} | ${a.title.replace(/\|/g, "/")} | ${a.creator || "n/a"} | ${a.license} | [${a.source_provider}](${a.source_page}) | ${a.channels.join(", ")} | ${a.intended_use.replace(/\|/g, "/")} | ${f(m.duration_s)} s | ${f(m.integrated_lufs)} | ${f(m.true_peak_dbtp)}${clip} | ${a.licence_verified_at_source === true ? "yes" : "NO"} | ${((qa[a.slot] || {}).machine_flags || []).length ? ((qa[a.slot] || {}).machine_flags || []).map((f) => f.replace(/\|/g, "/")).join("; ") : "none"} | ${(qa[a.slot] || {}).approval || "n/a"} |`;
});
const by = lib.assets.filter((a) => /^by/.test(a.license));
const md = `# Sound library register

Generated by \`platform/longform/v2/audio/register.mjs\` from \`config/longform-audio-library.json\` (retrieved ${lib.retrieved}, measured ${lib.measured_on}, via ${lib.via}). Do not edit by hand.

## What this is and is not

- ${lib.assets.length} assets, each downloaded to \`output/longform-media/audio/\` (not committed), decoded and measured with ffmpeg \`ebur128\`, and its **licence re-checked at the source page** (the page must contain the licence URL the aggregator reported). Column "Licence confirmed at source" is that check, not a legal opinion.
- **No asset has been auditioned by ear.** Choices came from title/tag/licence metadata and measurements. A person must listen to every music bed and every effect before a render; \`auditioned_by_ear\` is false everywhere on purpose.
- Policy: only CC0 / public domain / CC BY. CC BY-SA and any NC/ND licence are excluded (synchronising a track with video can be treated as an adaptation that carries ShareAlike). Free-to-download is not treated as cleared for commercial use.
- **${by.length} assets are CC BY and need on-screen/description attribution**: see the attribution list below. CC0 assets need none.
- One music file is not reused across every channel: the music slots are assigned to different channels (see "channels"), with alternatives to be added if a bed fails audition.
- Assets that peak at or above 0 dBTP are flagged CLIPS: they must be gain-staged down before mixing, never used as delivered.
- Loudness values of effects and ambiences are for gain staging only: effects are placed by purpose and level in the cue sheet, not normalised to a target.

## Register

| Slot | Kind | Title | Creator | Licence | Source | Channels | Intended use | Duration | LUFS | True peak dBTP | Licence confirmed at source | Machine QA flags (not a listening review) | Approval status |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## Attribution required (CC BY)

${by.map((a) => `- ${a.slot}: ${a.attribution}`).join("\n")}

## Listening review record (to be completed by a person: NOT done)

No one has listened to these assets. \`output/longform-audio-demo/audition-reel.mp3\` plays an excerpt of every asset in the order below (each excerpt loudness-matched to -23 LUFS for comfort; the real levels are in the table above), and \`audition-index.json\` maps reel time to slot. For each asset a listener records: heard in full (play the source file, not just the excerpt), noise/distortion/clipping, abrupt ending, loop problems, emotional tone, channel/scene suitability, and a decision: approved, rejected, or needs editing. Listening conditions (headphones model, speakers) must be written down with the decision.

| Slot | Reel time | Heard in full | Defects heard | Tone / suitability | Decision (approved / rejected / needs editing) | Listening conditions | Listener, date |
|---|---|---|---|---|---|---|---|
${lib.assets.map((a) => `| ${a.slot} | ${Math.floor(reel[a.slot] / 60)}:${String(Math.round(reel[a.slot] % 60)).padStart(2, "0")} | | | | | | |`).join(String.fromCharCode(10))}

## Known gaps

${lib.assets.length < 38 ? "- Slots with no licence-clean candidate found at the time of search were dropped, not filled with something unverified.\n" : ""}- No licensed football match audio, press-conference or broadcast ambience exists in this library; Rival Lines and Celebrity News effects are generic crowd/ambience beds only.
- BBC Sound Effects (RemArc licence) is for personal/educational/research use: **not used**. Freesound requires an API key and per-file licence handling: not yet used. Sonniss GDC bundles and Pixabay audio: not downloaded because their licence terms were not verified for this project in this pass.
`;
writeFileSync(join(ROOT, "docs/longform/SOUND-LIBRARY-REGISTER.md"), md);
console.log("wrote docs/longform/SOUND-LIBRARY-REGISTER.md", lib.assets.length, "assets");
